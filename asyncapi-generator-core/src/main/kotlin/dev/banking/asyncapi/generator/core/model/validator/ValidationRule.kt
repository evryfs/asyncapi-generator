package dev.banking.asyncapi.generator.core.model.validator

import dev.banking.asyncapi.generator.core.model.validator.ValidationConcern.ADVISORY
import dev.banking.asyncapi.generator.core.model.validator.ValidationConcern.GENERATOR_CAPABILITY
import dev.banking.asyncapi.generator.core.model.validator.ValidationConcern.SPECIFICATION
import dev.banking.asyncapi.generator.core.model.validator.ValidationSeverity.ERROR
import dev.banking.asyncapi.generator.core.model.validator.ValidationSeverity.WARNING

private const val ASYNCAPI_SPEC = "https://www.asyncapi.com/docs/reference/specification/v3.0.0"
private const val JSON_SCHEMA_KEYWORDS = "https://www.learnjsonschema.com/draft7/validation"
private const val KAFKA_BINDING = "https://www.asyncapi.com/docs/reference/bindings/kafka"
private const val PROJECT_RULES =
    "https://github.com/evryfs/asyncapi-generator/blob/main/docs/reference/validation-rules.md"

private fun spec(anchor: String) = "$ASYNCAPI_SPEC#$anchor"

private fun jsonSchema(keyword: String) = "$JSON_SCHEMA_KEYWORDS/$keyword/"

private fun kafkaBinding(anchor: String? = null) = anchor?.let { "$KAFKA_BINDING#$it" } ?: KAFKA_BINDING

/**
 * Stable identity and ownership metadata for a validation rule.
 *
 * The enum name is the code without its prefix; `JSONSCHEMA-` codes keep a `SCHEMA_` prefix.
 *
 * @property code the stable public identity of the rule
 * @property concern who owns the rule
 * @property severity whether a finding fails the load
 * @param reference the specification section that defines the rule; `GEN-` and `ADV-` rules have none and link
 *   to their row in the rule inventory
 */
enum class ValidationRule(
    val code: String,
    val concern: ValidationConcern,
    val severity: ValidationSeverity,
    private val reference: String? = null,
) {
    DOCUMENT_ID_FORMAT("AAS3-DOCUMENT-ID-FORMAT", SPECIFICATION, ERROR, spec("A2SIdString")),
    DOCUMENT_ID_URN("ADV-DOCUMENT-ID-URN", ADVISORY, WARNING),
    DOCUMENT_CONTENT_TYPE("AAS3-DOCUMENT-CONTENT-TYPE", SPECIFICATION, ERROR, spec("defaultContentTypeString")),

    INFO_TITLE_REQUIRED("AAS3-INFO-TITLE-REQUIRED", SPECIFICATION, ERROR, spec("infoObject")),
    INFO_VERSION_REQUIRED("AAS3-INFO-VERSION-REQUIRED", SPECIFICATION, ERROR, spec("infoObject")),

    INFO_TERMS_URI("AAS3-INFO-TERMS-URI", SPECIFICATION, ERROR, spec("infoObject")),
    CONTACT_URL_FORMAT("AAS3-CONTACT-URL-FORMAT", SPECIFICATION, ERROR, spec("contactObject")),
    CONTACT_EMAIL_FORMAT("AAS3-CONTACT-EMAIL-FORMAT", SPECIFICATION, ERROR, spec("contactObject")),
    LICENSE_NAME_REQUIRED("AAS3-LICENSE-NAME-REQUIRED", SPECIFICATION, ERROR, spec("licenseObject")),
    LICENSE_URL_FORMAT("AAS3-LICENSE-URL-FORMAT", SPECIFICATION, ERROR, spec("licenseObject")),

    SERVER_HOST_REQUIRED("AAS3-SERVER-HOST-REQUIRED", SPECIFICATION, ERROR, spec("serverObject")),
    SERVER_NAME_FORMAT("AAS3-SERVER-NAME-FORMAT", SPECIFICATION, ERROR, spec("serversObject")),
    COMPONENT_NAME_FORMAT("AAS3-COMPONENT-NAME-FORMAT", SPECIFICATION, ERROR, spec("componentsObject")),
    SERVER_HOST_PROTOCOL("ADV-SERVER-HOST-PROTOCOL", ADVISORY, WARNING),
    SERVER_VARIABLE_UNDEFINED("AAS3-SERVER-VARIABLE-UNDEFINED", SPECIFICATION, ERROR, spec("serverObject")),
    SERVER_PROTOCOL_REQUIRED("AAS3-SERVER-PROTOCOL-REQUIRED", SPECIFICATION, ERROR, spec("serverObject")),
    SERVER_VARIABLE_ENUM_UNIQUE("AAS3-SERVER-VARIABLE-ENUM-UNIQUE", SPECIFICATION, ERROR, spec("serverVariableObject")),
    SERVER_VARIABLE_DEFAULT_ENUM("ADV-SERVER-VARIABLE-DEFAULT-ENUM", ADVISORY, WARNING),
    SERVER_VARIABLE_EXAMPLES_ENUM("ADV-SERVER-VARIABLE-EXAMPLES-ENUM", ADVISORY, WARNING),

    CHANNEL_ADDRESS_SUFFIX("AAS3-CHANNEL-ADDRESS-SUFFIX", SPECIFICATION, ERROR, spec("channelObject")),
    CHANNEL_PARAMETER_UNDEFINED("AAS3-CHANNEL-PARAMETER-UNDEFINED", SPECIFICATION, ERROR, spec("parametersObject")),
    CHANNEL_PARAMETER_UNUSED("AAS3-CHANNEL-PARAMETER-UNUSED", SPECIFICATION, ERROR, spec("channelObject")),

    PARAMETER_ENUM_UNIQUE("AAS3-PARAMETER-ENUM-UNIQUE", SPECIFICATION, ERROR, spec("parameterObject")),
    PARAMETER_NAME_FORMAT("AAS3-PARAMETER-NAME-FORMAT", SPECIFICATION, ERROR, spec("parametersObject")),
    PARAMETER_DEFAULT_ENUM("ADV-PARAMETER-DEFAULT-ENUM", ADVISORY, WARNING),
    PARAMETER_EXAMPLES_ENUM("ADV-PARAMETER-EXAMPLES-ENUM", ADVISORY, WARNING),
    PARAMETER_LOCATION("AAS3-PARAMETER-LOCATION", SPECIFICATION, ERROR, spec("parameterObject")),
    CORRELATION_LOCATION_REQUIRED(
        "AAS3-CORRELATION-LOCATION-REQUIRED",
        SPECIFICATION,
        ERROR,
        spec("correlationIdObject"),
    ),
    CORRELATION_LOCATION_FORMAT("AAS3-CORRELATION-LOCATION-FORMAT", SPECIFICATION, ERROR, spec("correlationIdObject")),
    EXTERNAL_DOC_URL_REQUIRED(
        "AAS3-EXTERNAL-DOC-URL-REQUIRED",
        SPECIFICATION,
        ERROR,
        spec("externalDocumentationObject"),
    ),
    EXTERNAL_DOC_URL_FORMAT("AAS3-EXTERNAL-DOC-URL-FORMAT", SPECIFICATION, ERROR, spec("externalDocumentationObject")),
    TAG_NAME_REQUIRED("AAS3-TAG-NAME-REQUIRED", SPECIFICATION, ERROR, spec("tagObject")),

    MESSAGE_CONTENT_TYPE("AAS3-MESSAGE-CONTENT-TYPE", SPECIFICATION, ERROR, spec("messageObject")),
    MESSAGE_EXAMPLE_CONTENT("AAS3-MESSAGE-EXAMPLE-CONTENT", SPECIFICATION, ERROR, spec("messageExampleObject")),
    MESSAGE_EXAMPLE_SCHEMA("AAS3-MESSAGE-EXAMPLE-SCHEMA", SPECIFICATION, ERROR, spec("messageExampleObject")),
    MESSAGE_EXAMPLE_FORMAT("GEN-MESSAGE-EXAMPLE-FORMAT", GENERATOR_CAPABILITY, WARNING),
    MESSAGE_HEADER_FORMAT("GEN-MESSAGE-HEADER-FORMAT", GENERATOR_CAPABILITY, WARNING),

    OPERATION_ACTION_REQUIRED("AAS3-OPERATION-ACTION-REQUIRED", SPECIFICATION, ERROR, spec("operationObject")),
    OPERATION_ACTION_VALUE("AAS3-OPERATION-ACTION-VALUE", SPECIFICATION, ERROR, spec("operationObject")),
    OPERATION_CHANNEL_TARGET("AAS3-OPERATION-CHANNEL-TARGET", SPECIFICATION, ERROR, spec("operationObject")),
    OPERATION_CHANNEL_SCOPE("AAS3-OPERATION-CHANNEL-SCOPE", SPECIFICATION, ERROR, spec("operationObject")),
    OPERATION_MESSAGE_REFERENCE(
        "AAS3-OPERATION-MESSAGE-REFERENCE",
        SPECIFICATION,
        ERROR,
        spec("operationObjectMessages"),
    ),
    REPLY_CHANNEL_REQUIRED("AAS3-REPLY-CHANNEL-REQUIRED", SPECIFICATION, ERROR, spec("operationReplyObject")),
    REPLY_CHANNEL_SCOPE("AAS3-REPLY-CHANNEL-SCOPE", SPECIFICATION, ERROR, spec("operationReplyObject")),
    REPLY_CHANNEL_ADDRESS("AAS3-REPLY-CHANNEL-ADDRESS", SPECIFICATION, ERROR, spec("operationReplyObject")),
    REPLY_MESSAGE_REFERENCE("AAS3-REPLY-MESSAGE-REFERENCE", SPECIFICATION, ERROR, spec("operationReplyObject")),
    REPLY_ADDRESS_REQUIRED("AAS3-REPLY-ADDRESS-REQUIRED", SPECIFICATION, ERROR, spec("operationReplyAddressObject")),
    REPLY_ADDRESS_FORMAT("AAS3-REPLY-ADDRESS-FORMAT", SPECIFICATION, ERROR, spec("operationReplyAddressObject")),

    SECURITY_TYPE_REQUIRED("AAS3-SECURITY-TYPE-REQUIRED", SPECIFICATION, ERROR, spec("securitySchemeObject")),
    SECURITY_TYPE_VALUE("AAS3-SECURITY-TYPE-VALUE", SPECIFICATION, ERROR, spec("securitySchemeObject")),
    SECURITY_NAME_REQUIRED("AAS3-SECURITY-NAME-REQUIRED", SPECIFICATION, ERROR, spec("securitySchemeObject")),
    SECURITY_IN_REQUIRED("AAS3-SECURITY-IN-REQUIRED", SPECIFICATION, ERROR, spec("securitySchemeObject")),
    SECURITY_IN_VALUE("AAS3-SECURITY-IN-VALUE", SPECIFICATION, ERROR, spec("securitySchemeObject")),
    SECURITY_SCHEME_REQUIRED("AAS3-SECURITY-SCHEME-REQUIRED", SPECIFICATION, ERROR, spec("securitySchemeObject")),
    SECURITY_OAUTH_FLOWS("AAS3-SECURITY-OAUTH-FLOWS", SPECIFICATION, ERROR, spec("oauthFlowsObject")),
    OAUTH_AUTHORIZATION_URL_REQUIRED(
        "AAS3-OAUTH-AUTHORIZATION-URL-REQUIRED",
        SPECIFICATION,
        ERROR,
        spec("oauthFlowObject"),
    ),
    OAUTH_AUTHORIZATION_URL_FORMAT(
        "AAS3-OAUTH-AUTHORIZATION-URL-FORMAT",
        SPECIFICATION,
        ERROR,
        spec("oauthFlowObject"),
    ),
    OAUTH_TOKEN_URL_REQUIRED("AAS3-OAUTH-TOKEN-URL-REQUIRED", SPECIFICATION, ERROR, spec("oauthFlowObject")),
    OAUTH_TOKEN_URL_FORMAT("AAS3-OAUTH-TOKEN-URL-FORMAT", SPECIFICATION, ERROR, spec("oauthFlowObject")),
    OAUTH_REFRESH_URL_FORMAT("AAS3-OAUTH-REFRESH-URL-FORMAT", SPECIFICATION, ERROR, spec("oauthFlowObject")),
    OAUTH_SCOPE_AVAILABLE("AAS3-OAUTH-SCOPE-AVAILABLE", SPECIFICATION, ERROR, spec("oauthFlowObject")),
    SECURITY_OPENID_URL_REQUIRED(
        "AAS3-SECURITY-OPENID-URL-REQUIRED",
        SPECIFICATION,
        ERROR,
        spec("securitySchemeObject"),
    ),
    SECURITY_OPENID_URL_FORMAT("AAS3-SECURITY-OPENID-URL-FORMAT", SPECIFICATION, ERROR, spec("securitySchemeObject")),

    BINDING_PROTOCOL_TYPE("AAS3-BINDING-PROTOCOL-TYPE", SPECIFICATION, ERROR, spec("definitionsBindings")),
    KAFKA_BINDING_VERSION_TYPE("AAS3-KAFKA-BINDING-VERSION-TYPE", SPECIFICATION, ERROR, kafkaBinding()),
    KAFKA_BINDING_VERSION("GEN-KAFKA-BINDING-VERSION", GENERATOR_CAPABILITY, ERROR),
    KAFKA_BINDING_FIELD("AAS3-KAFKA-BINDING-FIELD", SPECIFICATION, ERROR, kafkaBinding()),
    KAFKA_BINDING_FIELD_TYPE("AAS3-KAFKA-BINDING-FIELD-TYPE", SPECIFICATION, ERROR, kafkaBinding()),
    KAFKA_CHANNEL_POSITIVE_INTEGER(
        "AAS3-KAFKA-CHANNEL-POSITIVE-INTEGER",
        SPECIFICATION,
        ERROR,
        kafkaBinding("channel"),
    ),
    KAFKA_SCHEMA_REGISTRY_URL("AAS3-KAFKA-SCHEMA-REGISTRY-URL", SPECIFICATION, ERROR, kafkaBinding("server")),
    KAFKA_SCHEMA_REGISTRY_VENDOR_URL(
        "AAS3-KAFKA-SCHEMA-REGISTRY-VENDOR-URL",
        SPECIFICATION,
        ERROR,
        kafkaBinding("server"),
    ),
    KAFKA_MESSAGE_SCHEMA_REGISTRY_URL(
        "AAS3-KAFKA-MESSAGE-SCHEMA-REGISTRY-URL",
        SPECIFICATION,
        ERROR,
        kafkaBinding("message"),
    ),
    KAFKA_CLEANUP_POLICY("AAS3-KAFKA-CLEANUP-POLICY", SPECIFICATION, ERROR, kafkaBinding("topicConfiguration")),

    REFERENCE_UNRESOLVED("AAS3-REFERENCE-UNRESOLVED", SPECIFICATION, ERROR, spec("referenceObject")),
    REFERENCE_CATEGORY_REQUIRED("GEN-REFERENCE-CATEGORY-REQUIRED", GENERATOR_CAPABILITY, ERROR),
    REFERENCE_TARGET_CATEGORY("AAS3-REFERENCE-TARGET-CATEGORY", SPECIFICATION, ERROR, spec("referenceObject")),
    REFERENCE_CYCLE("AAS3-REFERENCE-CYCLE", SPECIFICATION, ERROR, spec("referenceObject")),

    SCHEMA_KEYWORD_UNSUPPORTED("GEN-SCHEMA-KEYWORD-UNSUPPORTED", GENERATOR_CAPABILITY, ERROR),
    SCHEMA_ANNOTATION_IGNORED("GEN-SCHEMA-ANNOTATION-IGNORED", GENERATOR_CAPABILITY, WARNING),
    SCHEMA_DEPENDENCY_ARRAY_UNIQUE(
        "JSONSCHEMA-DEPENDENCY-ARRAY-UNIQUE",
        SPECIFICATION,
        ERROR,
        jsonSchema("dependencies"),
    ),
    SCHEMA_DIALECT("GEN-SCHEMA-DIALECT", GENERATOR_CAPABILITY, ERROR),
    SCHEMA_TYPE("JSONSCHEMA-TYPE", SPECIFICATION, ERROR, jsonSchema("type")),
    SCHEMA_TYPE_ARRAY_NONEMPTY("JSONSCHEMA-TYPE-ARRAY-NONEMPTY", SPECIFICATION, ERROR, jsonSchema("type")),
    SCHEMA_TYPE_ARRAY_UNIQUE("JSONSCHEMA-TYPE-ARRAY-UNIQUE", SPECIFICATION, ERROR, jsonSchema("type")),
    SCHEMA_ENUM_NONEMPTY("JSONSCHEMA-ENUM-NONEMPTY", SPECIFICATION, ERROR, jsonSchema("enum")),
    SCHEMA_ENUM_UNIQUE("JSONSCHEMA-ENUM-UNIQUE", SPECIFICATION, ERROR, jsonSchema("enum")),
    SCHEMA_CONST_TYPE("GEN-SCHEMA-CONST-TYPE", GENERATOR_CAPABILITY, ERROR),
    SCHEMA_NUMERIC_RANGE("GEN-SCHEMA-NUMERIC-RANGE", GENERATOR_CAPABILITY, ERROR),
    SCHEMA_MULTIPLE_OF("JSONSCHEMA-MULTIPLE-OF", SPECIFICATION, ERROR, jsonSchema("multipleof")),
    SCHEMA_STRING_LENGTH("JSONSCHEMA-STRING-LENGTH", SPECIFICATION, ERROR, jsonSchema("maxlength")),
    SCHEMA_STRING_LENGTH_RANGE("GEN-SCHEMA-STRING-LENGTH-RANGE", GENERATOR_CAPABILITY, ERROR),
    SCHEMA_ARRAY_SIZE("JSONSCHEMA-ARRAY-SIZE", SPECIFICATION, ERROR, jsonSchema("maxitems")),
    SCHEMA_ARRAY_SIZE_RANGE("GEN-SCHEMA-ARRAY-SIZE-RANGE", GENERATOR_CAPABILITY, ERROR),
    SCHEMA_OBJECT_SIZE("JSONSCHEMA-OBJECT-SIZE", SPECIFICATION, ERROR, jsonSchema("maxproperties")),
    SCHEMA_OBJECT_SIZE_RANGE("GEN-SCHEMA-OBJECT-SIZE-RANGE", GENERATOR_CAPABILITY, ERROR),
    SCHEMA_REQUIRED_UNIQUE("JSONSCHEMA-REQUIRED-UNIQUE", SPECIFICATION, ERROR, jsonSchema("required")),
    SCHEMA_REQUIRED_UNDECLARED("GEN-SCHEMA-REQUIRED-UNDECLARED", GENERATOR_CAPABILITY, WARNING),
    SCHEMA_DEFAULT_TYPE("GEN-SCHEMA-DEFAULT-TYPE", GENERATOR_CAPABILITY, ERROR),
    SCHEMA_DISCRIMINATOR_REQUIRED(
        "AAS3-SCHEMA-DISCRIMINATOR-REQUIRED",
        SPECIFICATION,
        ERROR,
        spec("schemaObjectDiscriminator"),
    ),
    SCHEMA_DISCRIMINATOR_PROPERTY(
        "AAS3-SCHEMA-DISCRIMINATOR-PROPERTY",
        SPECIFICATION,
        ERROR,
        spec("schemaObjectDiscriminator"),
    ),
    UNION_INDISTINGUISHABLE_MEMBERS("ADV-UNION-INDISTINGUISHABLE-MEMBERS", ADVISORY, WARNING),
    ;

    /** Where the rule is documented: its specification section, or its row in the rule inventory. */
    val documentation: String
        get() = reference ?: "$PROJECT_RULES#${code.lowercase()}"
}
