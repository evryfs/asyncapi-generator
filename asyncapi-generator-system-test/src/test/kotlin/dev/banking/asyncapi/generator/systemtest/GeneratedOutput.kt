package dev.banking.asyncapi.generator.systemtest

import java.io.File
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * Everything a frontend generated for a scenario.
 *
 * Files from all output directories are merged by their path relative to the
 * output directory, so a frontend that shares one directory between executions
 * (Maven's default) compares equal to one that uses a directory per execution
 * (Gradle's default). Bundled documents are keyed by their configured path.
 *
 * @property files File contents keyed by `/`-separated relative path.
 */
internal data class GeneratedOutput(val files: Map<String, String>) {

    companion object {
        fun read(run: FrontendRun): GeneratedOutput {
            val generated = run.outputDirectories.values.distinct().flatMap { directory -> readDirectory(directory).toList() }
            val documents = run.outputFiles.map { (id, file) ->
                assertTrue(file.isFile, "Expected execution '$id' to write the bundled document $file")
                "$OUTPUT_FILE_PREFIX$id" to file.readText()
            }
            return GeneratedOutput((generated + documents).toMap().toSortedMap())
        }

        fun readDirectory(root: File): Map<String, String> =
            root.walkTopDown()
                .filter(File::isFile)
                .associate { it.relativeTo(root).invariantSeparatorsPath to it.readText() }

        private const val OUTPUT_FILE_PREFIX = "outputFile of "
    }
}

/** Asserts that every frontend produced the same files with the same content as the first one. */
internal fun assertSameOutput(outputs: Map<String, GeneratedOutput>) {
    val (referenceName, reference) = outputs.entries.first()
    outputs.entries.drop(1).forEach { (name, output) ->
        assertEquals(reference.files.keys, output.files.keys, "Generated file set of $name differs from $referenceName")
        reference.files.forEach { (path, content) ->
            assertEquals(content, output.files.getValue(path), "$path generated by $name differs from $referenceName")
        }
    }
}

/**
 * Asserts that executions configured without any package wrote no sources or schemas.
 *
 * Only output directories used exclusively by such executions are checked; the
 * directory may exist (Gradle creates declared output directories) but must be empty.
 */
internal fun assertNoArtifactsWithoutPackages(scenario: Scenario, run: FrontendRun) {
    val executionsByDirectory = scenario.executions.groupBy { run.outputDirectories.getValue(it.id).canonicalFile }
    executionsByDirectory
        .filterValues { executions -> executions.none(Execution::generatesArtifacts) }
        .forEach { (directory, executions) ->
            val files = if (directory.isDirectory) GeneratedOutput.readDirectory(directory).keys else emptySet()
            assertTrue(
                files.isEmpty(),
                "Executions ${executions.map(Execution::id)} configure no package but wrote $files to $directory",
            )
        }
}
